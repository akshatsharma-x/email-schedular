import { users } from '../db/schema.js';
import { closeDb, db } from '../db/client.js';
import { runMigrations } from '../db/migrate.js';
import { logger } from '../lib/logger.js';
import { listAvailableSenders } from '../mailer/senderPool.js';
import { planSchedule, summarisePlan } from '../queue/planner.js';
import { scheduleCampaign } from '../queue/scheduler.js';
import { closeQueues } from '../queue/queues.js';
import { closeRedis } from '../lib/redis.js';
import { env } from '../config/env.js';

const log = logger.child({ script: 'loadtest' });

/**
 * Schedules a large campaign to demonstrate behaviour under load.
 *
 *   npm run loadtest -- --count 1000
 *   npm run loadtest -- --count 1000 --dry-run     (plan only, nothing written)
 *
 * Addresses are generated at @example.com, which Ethereal accepts and discards,
 * so a thousand jobs can be exercised without spamming anyone.
 *
 * `--dry-run` prints just the computed plan: the per-hour spread, how many hour
 * windows the campaign occupies, and the predicted finish time. That is the
 * fastest way to see how the system answers "1000 emails scheduled for the same
 * instant" without waiting for it to drain.
 */

interface Args {
  count: number;
  dryRun: boolean;
  startInSeconds: number;
  minDelayMs?: number;
  maxPerHour?: number;
}

function parseArgs(argv: string[]): Args {
  const args: Args = { count: 1000, dryRun: false, startInSeconds: 5 };
  for (let i = 0; i < argv.length; i += 1) {
    const flag = argv[i];
    const value = argv[i + 1];
    if (flag === '--count' && value) {
      args.count = Math.max(1, Number(value));
      i += 1;
    } else if (flag === '--dry-run') {
      args.dryRun = true;
    } else if (flag === '--start-in' && value) {
      args.startInSeconds = Number(value);
      i += 1;
    } else if (flag === '--min-delay' && value) {
      args.minDelayMs = Number(value);
      i += 1;
    } else if (flag === '--per-hour' && value) {
      args.maxPerHour = Number(value);
      i += 1;
    }
  }
  return args;
}

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  await runMigrations();

  const [user] = await db.select().from(users).orderBy(users.createdAt).limit(1);
  if (!user) {
    log.error('no user found -- run `npm run senders:create` first');
    process.exit(1);
  }

  const pool = await listAvailableSenders(user.id);
  if (pool.length === 0) {
    log.error('no active senders -- run `npm run senders:create -- --count 2`');
    process.exit(1);
  }

  const startAt = new Date(Date.now() + args.startInSeconds * 1000);
  const minDelayMs = args.minDelayMs ?? env.MIN_DELAY_BETWEEN_EMAILS_MS;
  const perSenderHourly = args.maxPerHour ?? env.MAX_EMAILS_PER_HOUR_PER_SENDER;

  const planInput = {
    recipientCount: args.count,
    senderCount: pool.length,
    startAt: startAt.getTime(),
    minDelayMs,
    perSenderHourly,
  };

  if (args.dryRun) {
    const summary = summarisePlan(planSchedule(planInput), planInput);
    console.log('\n  Plan (dry run -- nothing written)\n');
    console.log(`  recipients:        ${summary.totalEmails}`);
    console.log(`  senders:           ${summary.senderCount}`);
    console.log(`  per-sender/hour:   ${summary.perSenderHourly}`);
    console.log(`  min delay:         ${summary.effectiveMinDelayMs} ms`);
    console.log(`  first send:        ${summary.firstSendAt}`);
    console.log(`  last send:         ${summary.lastSendAt}`);
    console.log(`  span:              ${summary.spanMinutes} min`);
    console.log(`  hour windows used: ${summary.windowsUsed}`);
    console.log(
      `  aggregate rate:    ${summary.senderCount * summary.perSenderHourly} emails/hour\n`,
    );
    await closeDb();
    await closeQueues();
    await closeRedis();
    return;
  }

  const leads = Array.from({ length: args.count }, (_, i) => ({
    // example.com is reserved by RFC 2606 -- safe to generate in bulk.
    email: `load-test-${Date.now()}-${i}@example.com`,
    name: `Load Lead ${i}`,
  }));

  const started = Date.now();
  const result = await scheduleCampaign({
    userId: user.id,
    subject: `Load test ${new Date().toISOString()}`,
    body: 'This is a load-test message generated by npm run loadtest.',
    name: `Load test ${args.count}`,
    leads,
    startAt,
    minDelayMs,
    maxPerHour: perSenderHourly,
  });

  console.log('\n  Scheduled\n');
  console.log(`  campaign:          ${result.campaign.id}`);
  console.log(`  recipients:        ${result.plan.totalEmails}`);
  console.log(`  enqueued:          ${result.enqueued}`);
  console.log(`  senders:           ${result.plan.senderCount}`);
  console.log(`  first send:        ${result.plan.firstSendAt}`);
  console.log(`  last send:         ${result.plan.lastSendAt}`);
  console.log(`  span:              ${result.plan.spanMinutes} min`);
  console.log(`  hour windows used: ${result.plan.windowsUsed}`);
  console.log(`  took:              ${Date.now() - started} ms\n`);

  await closeDb();
  await closeQueues();
  await closeRedis();
}

main().catch((err) => {
  log.error({ err }, 'loadtest failed');
  process.exit(1);
});
